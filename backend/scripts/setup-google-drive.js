#!/usr/bin/env node

/**
 * Helper script để setup Google Drive backup credentials
 * Usage: node scripts/setup-google-drive.js [path-to-json-file]
 */

const fs = require('fs');
const path = require('path');
const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
});

function ask(question) {
  return new Promise(resolve => rl.question(question, resolve));
}

async function main() {
  console.log('\n🔧 Google Drive Backup Setup Helper\n');
  console.log('Công cụ này sẽ giúp bạn cấu hình Google Drive credentials.\n');

  // Check if JSON file path provided as argument
  let jsonFilePath = process.argv[2];

  if (!jsonFilePath) {
    jsonFilePath = await ask('Nhập đường dẫn đến file JSON key (hoặc Enter để bỏ qua): ');
  }

  let credentials;

  if (jsonFilePath && jsonFilePath.trim() !== '') {
    // Read from file
    const fullPath = path.resolve(jsonFilePath.trim());
    
    if (!fs.existsSync(fullPath)) {
      console.error(`❌ Không tìm thấy file: ${fullPath}`);
      process.exit(1);
    }

    try {
      const content = fs.readFileSync(fullPath, 'utf-8');
      credentials = JSON.parse(content);
      console.log('✅ Đọc file JSON thành công!');
    } catch (err) {
      console.error(`❌ Lỗi đọc file JSON: ${err.message}`);
      process.exit(1);
    }
  } else {
    console.log('\nSkip - Bạn cần paste JSON credentials manually vào file .env');
    console.log('Xem hướng dẫn chi tiết tại README.md\n');
    process.exit(0);
  }

  // Validate credentials
  if (!credentials.client_email || !credentials.private_key) {
    console.error('❌ File JSON không đúng format Service Account (thiếu client_email hoặc private_key)');
    process.exit(1);
  }

  console.log(`\n📧 Service Account Email: ${credentials.client_email}`);

  // Ask for folder ID
  const folderId = await ask('\nNhập Google Drive Folder ID: ');
  
  if (!folderId || folderId.trim() === '') {
    console.error('❌ Folder ID không được để trống');
    process.exit(1);
  }

  // Minify JSON (remove whitespace)
  const minifiedJson = JSON.stringify(credentials);

  // Prepare .env content
  const envContent = `
# ─────────────────────────────────────────────────────────────────────────────
# Google Drive Backup Configuration (Auto-generated by setup script)
# ─────────────────────────────────────────────────────────────────────────────
GOOGLE_DRIVE_FOLDER_ID=${folderId.trim()}
GOOGLE_SERVICE_ACCOUNT_JSON=${minifiedJson}

# Backup settings
BACKUP_AUTO_ENABLED=true
BACKUP_CRON_SCHEDULE="0 2 * * *"
BACKUP_RETENTION_COUNT=7
`;

  console.log('\n📝 Nội dung cần thêm vào file .env:\n');
  console.log('─'.repeat(80));
  console.log(envContent);
  console.log('─'.repeat(80));

  const confirm = await ask('\nBạn có muốn tự động append vào backend/.env? (y/n): ');
  
  if (confirm.toLowerCase() === 'y') {
    const envPath = path.join(__dirname, '..', '.env');
    
    try {
      // Backup existing .env
      if (fs.existsSync(envPath)) {
        const backup = `${envPath}.backup.${Date.now()}`;
        fs.copyFileSync(envPath, backup);
        console.log(`\n💾 Đã backup .env hiện tại sang: ${path.basename(backup)}`);
      }

      // Append new content
      fs.appendFileSync(envPath, envContent);
      console.log('✅ Đã cập nhật file .env thành công!');
      
      console.log('\n🎉 Setup hoàn tất! Các bước tiếp theo:');
      console.log('1. Đảm bảo bạn đã Share thư mục Google Drive với email:');
      console.log(`   ${credentials.client_email}`);
      console.log('   (với quyền "Editor" / "Người chỉnh sửa")');
      console.log('2. Khởi động backend: npm run dev');
      console.log('3. Test kết nối: POST /api/backup/test-connection');
      console.log('4. Trigger backup thử: POST /api/backup/trigger\n');
      
    } catch (err) {
      console.error(`❌ Lỗi khi ghi file: ${err.message}`);
      process.exit(1);
    }
  } else {
    console.log('\n📋 Hãy copy nội dung phía trên và paste vào file backend/.env manually.');
  }

  rl.close();
}

main().catch(err => {
  console.error('❌ Lỗi:', err);
  process.exit(1);
});
